"""Precision@k / Recall@k table for the six downstream configurations.

Tabular form of figures/judged-precision-recall-at-k.pdf in the paper, with the
metric definitions of clean_notebook.ipynb (cells 22 and 25):

* relevance is the PoE label; the ranking unit is the source document
  (chunks ranked by cross-encoder score, deduplicated by file name);
* a query whose judged run has no relevant document falls back to its gold
  document as the only relevant one;
* the hybrid strategy is the RRF (k=60) fusion of the MMR and ensemble runs,
  cut to the top 10;
* the two evaluators are averaged within a query, then 95% percentile
  bootstrap CIs over queries (10,000 resamples, seed 42).

Run from this directory:  python judged_pr_table.py
"""

from collections import defaultdict
from pathlib import Path
import json

import numpy as np

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "outputs" / "results_split"
OUT = ROOT.parent / "paper-2026-automl-journal-version" / "figures" / "judged-precision-recall-at-k-table.tex"

KS = (1, 3, 5)
METRICS = [f"p@{k}" for k in KS] + [f"r@{k}" for k in KS]
N_BOOTSTRAP, SEED = 10_000, 42

STRATEGIES = {"ensemble": "Ensemble", "mmr": r"\ac{MMR}", "mmr+ensemble": "Hybrid"}
STORES = {"nomic-chatfaq": "nomic-v2-moe", "qwen-chatfaq": "qwen3-0.6b"}


def load_full_runs():
    recs = [json.loads(line)
            for f in sorted(RESULTS.glob("results_part_*.jsonl"))
            for line in f.open(encoding="utf-8") if line.strip()]
    return [r for r in recs if r["dataset"].endswith("__FULL")]


def rrf(ranked_lists, k=60):
    # dict, not set: ties keep first-seen order, so the top-10 cut is deterministic
    # (the notebook iterated a set of ids, whose order changes between runs)
    scores, docs = defaultdict(float), {}
    for lst in ranked_lists:
        for rank, d in enumerate(lst, 1):
            scores[d["id"]] += 1 / (k + rank)
            docs.setdefault(d["id"], d)
    return sorted(docs.values(), key=lambda d: -scores[d["id"]])


def add_hybrid(recs):
    by_query = defaultdict(dict)
    for r in recs:
        strategy, store, split = r["dataset"].split("__")
        by_query[(store, split, r["file_name"], r["botname"])][strategy] = r
    fused = []
    for (store, split, _, _), runs in by_query.items():
        if {"mmr", "ensemble"} <= runs.keys():
            top10 = rrf([runs["mmr"]["graded_docs"], runs["ensemble"]["graded_docs"]])[:10]
            fused.append({**runs["mmr"], "dataset": f"mmr+ensemble__{store}__{split}",
                          "graded_docs": top10})
    return recs + fused


def precision_recall(rec):
    docs = rec["graded_docs"]
    ranked = sorted(docs, key=lambda d: -(d["cross_encoder_score"]
                                           if d.get("cross_encoder_score") is not None else -999))
    ranked = list(dict.fromkeys(d["file_name"] for d in ranked))
    relevant = {d["file_name"] for d in docs if d.get("relevance") == "relevant"} or {rec["file_name"]}
    hits = {k: len(set(ranked[:k]) & relevant) for k in KS}
    return {**{f"p@{k}": hits[k] / k for k in KS},
            **{f"r@{k}": hits[k] / len(relevant) for k in KS}}


def bootstrap(values):
    values = np.asarray(values)
    idx = np.random.default_rng(SEED).integers(0, len(values), size=(N_BOOTSTRAP, len(values)))
    lo, hi = np.percentile(values[idx].mean(axis=1), [2.5, 97.5])
    return values.mean(), lo, hi


def per_query_scores(recs):
    """{dataset: {metric: per-query values, evaluators averaged within the query}}."""
    runs = defaultdict(lambda: defaultdict(list))
    for r in recs:
        runs[r["dataset"]][r["file_name"]].append(precision_recall(r))
    return {ds: {m: [np.mean([e[m] for e in evals]) for evals in queries.values()] for m in METRICS}
            for ds, queries in runs.items()}


def latex(stats, n_queries):
    ci = lambda lo, hi: rf"{{\scriptsize[{lo:.3f}, {hi:.3f}]}}"
    lines = [
        "% Auto-generated by poe-retrieval-experiment/judged_pr_table.py — do not edit by hand.",
        f"% Mean over {n_queries} queries, 95% bootstrap CI below. Requires booktabs, multirow.",
        r"\begin{tabular}{ll" + "c" * len(METRICS) + "}",
        r"    \toprule",
        "    Strategy & Vector store & " + " & ".join(m.upper() for m in METRICS) + r" \\",
        r"    \midrule",
    ]
    for i, (strategy, strategy_label) in enumerate(STRATEGIES.items()):
        if i:
            lines.append(r"    \midrule")
        for j, (store, store_label) in enumerate(STORES.items()):
            s = stats[f"{strategy}__{store}__FULL"]
            head = rf"\multirow{{{2 * len(STORES)}}}{{*}}{{{strategy_label}}}" if j == 0 else ""
            lines.append(f"    {head} & {store_label} & "
                         + " & ".join(f"{s[m][0]:.3f}" for m in METRICS) + r" \\")
            lines.append("     & & " + " & ".join(ci(*s[m][1:]) for m in METRICS) + r" \\")
    lines += [r"    \bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def main():
    scores = per_query_scores(add_hybrid(load_full_runs()))
    stats = {ds: {m: bootstrap(v) for m, v in ms.items()} for ds, ms in scores.items()}
    n_queries = {len(ms["p@1"]) for ms in scores.values()}
    assert len(n_queries) == 1, f"configurations cover different query sets: {n_queries}"
    for ds in sorted(stats):
        print(f"{ds:36s} " + " ".join(f"{m}={stats[ds][m][0]:.3f}" for m in METRICS))
    OUT.write_text(latex(stats, n_queries.pop()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
